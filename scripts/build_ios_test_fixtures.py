"""Generate Swift test fixtures from the Python side's own answers.

Two implementations of the same rule drift silently unless something pins them
together. This is that something: Python computes, Swift asserts.

Run: uv run python scripts/build_ios_test_fixtures.py
"""
from __future__ import annotations

import base64
import importlib.util
import json
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "ios" / "MonitorFinanceTests" / "Generated"

NAMESPACE = uuid.UUID("6f1c2a6e-5b7e-4d0c-9a1e-2b3c4d5e6f70")

CORPUS = REPO / "tests" / "fixtures" / "monobank_corpus.jsonl"
FIXTURES_DIR = REPO / "tests" / "fixtures"
CHECK_FIXTURE = FIXTURES_DIR / "fiscal_check_fuel.json"
# The seven real receipts from six register vendors (S1-S7). Ordinals 1-7,
# matching tests/fixtures/fiscal_check_{n}.json and tests/test_check_decode.py's
# own GOLDEN table.
SEVEN_CHECK_FIXTURES = [FIXTURES_DIR / f"fiscal_check_{n}.json" for n in range(1, 8)]

# Deliberately awkward: Cyrillic, a pipe, an empty string, a long name. A
# fixture of three ASCII words would pass for a UTF-16 implementation.
UUID5_NAMES = [
    "",
    "monobank|50h99c1tyP-4HO1FRw",
    "monobank|yJq-6cp-w4",
    "Продукти|Тестовий Магазин",
    "x" * 300,
]

HEADER = "// GENERATED by scripts/build_ios_test_fixtures.py — do not edit.\n"


def build_uuid5(out: Path) -> None:
    rows = "\n".join(
        f'        (name: {swift_string(name)}, uuid: "{uuid.uuid5(NAMESPACE, name)}"),'
        for name in UUID5_NAMES
    )
    out.write_text(
        f"{HEADER}\n"
        "enum UUIDv5Fixture {\n"
        '    static let namespace = "6f1c2a6e-5b7e-4d0c-9a1e-2b3c4d5e6f70"\n'
        "    static let cases: [(name: String, uuid: String)] = [\n"
        f"{rows}\n"
        "    ]\n"
        "}\n",
        encoding="utf-8",
    )


def swift_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def swift_optional_string(value: str | None) -> str:
    return "nil" if value is None else swift_string(value)


# The corpus carries real merchant text. Nothing real crosses into a Swift
# source; the structural fields, which are what the two implementations could
# disagree about, are untouched.
# The corpus fields whose STRING value is carried into the committed fixture
# verbatim. Board #82: an allowlist, not a list of things to scrub.
#
# `scrub` used to name `description` and `counterName` — the only free text
# the corpus happens to hold today. monobank's statement API also returns
# `comment`, `counterIban` and `counterEdrpou`, every one of which identifies
# a person, and a recapture that included any of them would have been copied
# into a committed file in silence. Naming what may pass through means a new
# field is scrubbed by default and has to be argued into this set.
#
# `id` is monobank's own opaque transaction token. It is here because the
# fixture's `uuid` is derived from it (`uuid5(NAMESPACE, "monobank|" + id)`)
# and that derivation is the thing `MonobankMapperTests` exists to pin —
# scrubbing it would replace the test's subject with a test of the scrubber.
# It carries no name, no account number and no free text.
CARRIED_VERBATIM = {"id"}

# Deterministic stand-ins, cycled so the fixture keeps a realistic spread of
# repeated and distinct values rather than 111 copies of one string.
_REPLACEMENTS = {
    "description": ("Продавець", 7),
    "counterName": ("Контрагент", 5),
}


def scrub(row: dict, n: int) -> dict:
    """Every string the corpus holds, replaced — except what is allowlisted.

    A field with no entry in `_REPLACEMENTS` still gets scrubbed; it just gets
    a generic stand-in named after itself. That is the point: the fallback has
    to be "replace", or the guard in `tests/test_ios_seed.py` is the only thing
    standing between a recaptured corpus and a committed leak, and a guard is a
    report rather than a defence.
    """
    out = dict(row)
    for field, value in row.items():
        if field in CARRIED_VERBATIM or not isinstance(value, str) or not value.strip():
            continue
        word, cycle = _REPLACEMENTS.get(field, (field.capitalize(), 5))
        out[field] = f"{word} {n % cycle}"
    return out


def build_mapper(out: Path) -> None:
    lines = CORPUS.read_text(encoding="utf-8").splitlines()
    rows = [json.loads(line) for line in lines if line.strip()]
    cases = []
    for n, raw in enumerate(rows):
        row = scrub(raw, n)
        blob = json.dumps(row, ensure_ascii=False, sort_keys=True)
        cases.append(
            "        .init(\n"
            f"            json: {swift_string(blob)},\n"
            f'            uuid: "{uuid.uuid5(NAMESPACE, "monobank|" + row["id"])}",\n'
            f'            time: {row["time"]},\n'
            f'            amount: {row["amount"]},\n'
            f'            kind: "{"income" if row["amount"] > 0 else "expense"}",\n'
            f"            merchant: {swift_string(row['description'].strip())},\n"
            f'            hold: {"true" if row.get("hold") else "false"}),'
        )
    body = "\n".join(cases)
    out.write_text(
        f"{HEADER}\n"
        "enum MonobankMapperFixture {\n"
        "    struct Case {\n"
        "        let json: String\n"
        "        let uuid: String\n"
        "        let time: Int\n"
        "        let amount: Int\n"
        "        let kind: String\n"
        "        let merchant: String\n"
        "        let hold: Bool\n"
        "    }\n"
        "    static let cases: [Case] = [\n"
        f"{body}\n"
        "    ]\n"
        "}\n",
        encoding="utf-8",
    )


def _load_check_decode():
    # Loaded by path, like `tests/test_check_decode.py` does — `scripts` is
    # not a package, so this is the reference decoder's own import route.
    spec = importlib.util.spec_from_file_location(
        "check_decode", REPO / "scripts" / "check_decode.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _parse_check_fixture(check_decode, path: Path) -> tuple[dict, dict, list[str]]:
    """One fixture's payload, Python's parse of it, and the free text (`<L>`
    text plus the cashier's `NDP_CSNM`) `CheckXML` must never surface. Walked
    off the actual XML rather than retyped, so a future re-scrub of the
    fixture keeps this in sync too.
    """
    payload = json.loads(path.read_text(encoding="utf-8"))
    raw = base64.b64decode(payload["checkXml"])
    parsed = check_decode.parse_xml(raw)

    text = raw.decode("cp1251").replace("windows-1251", "utf-8", 1)
    root = ET.fromstring(text)
    forbidden: list[str] = []
    for el in root.iter():
        if el.tag == "L" and el.text and el.text.strip():
            forbidden.append(el.text.strip())
        cashier = el.get("NDP_CSNM")
        if cashier:
            forbidden.append(cashier)
    must_not_appear = list(dict.fromkeys(forbidden))  # de-dupe, keep order
    return payload, parsed, must_not_appear


def _lines_block(lines: list[dict], indent: str) -> str:
    def row(line: dict) -> str:
        head = f"{indent}(ordinal: {line['ordinal']}, qtyMilli: {line['qty_milli']}, "
        head += f"grossSum: {line['gross_sum']},\n"
        tail = f"{indent} discount: {line['discount']}, netSum: {line['net_sum']}, "
        tail += f"netUnitPrice: {line['net_unit_price']}),"
        return head + tail

    return "\n".join(row(line) for line in lines)


def build_check(out: Path) -> None:
    """`CheckXML`'s pin. Python parses the same scrubbed real documents Swift
    will, and this writes both their base64 and Python's own answers into
    one generated file — so the Swift tests assert against Python's numbers,
    never against numbers a human retyped, and neither side can drift
    without the other going red.

    Two sections: the single fuel receipt (kept for the tests pinned against
    its specific shape — the windows-1251 name, the D9 free-text guard, the
    MAC), and all seven real receipts (S1-S7) in `CheckFixture.seven`, which
    is the parity pin that matters most — seven documents from six register
    vendors, two implementations, one set of numbers.
    """
    check_decode = _load_check_decode()

    payload, parsed, must_not_appear = _parse_check_fixture(check_decode, CHECK_FIXTURE)
    lines_rows = _lines_block(parsed["lines"], "        ")
    must_not_appear_rows = "\n".join(f"        {swift_string(m)}," for m in must_not_appear)

    seven_rows = []
    for n, path in enumerate(SEVEN_CHECK_FIXTURES, start=1):
        seven_payload, seven_parsed, seven_forbidden = _parse_check_fixture(check_decode, path)
        seven_rows.append(
            f"        {n}: CheckFixture.Document(\n"
            f"            base64: {swift_string(seven_payload['checkXml'])},\n"
            f"            registerModel: {swift_optional_string(seven_parsed['schema_version'])},\n"
            f"            fiscalTotal: {seven_parsed['fiscal_total']},\n"
            f"            mac: {swift_optional_string(seven_parsed['mac'])},\n"
            "            lines: [\n"
            f"{_lines_block(seven_parsed['lines'], '                ')}\n"
            "            ],\n"
            "            mustNotAppear: [\n"
            + "\n".join(f"                {swift_string(m)}," for m in seven_forbidden)
            + "\n"
            "            ]),"
        )
    seven_block = "\n".join(seven_rows)

    out.write_text(
        f"{HEADER}\n"
        "enum CheckFixture {\n"
        "    /// One real fiscal document, scrubbed of every name. Numbers untouched.\n"
        f"    static let base64 = {swift_string(payload['checkXml'])}\n"
        "\n"
        "    /// What `scripts/check_decode.py` reads out of it. Swift must agree.\n"
        f"    static let registerModel = {swift_optional_string(parsed['schema_version'])}\n"
        f"    static let fiscalTotal = {parsed['fiscal_total']}\n"
        f"    static let mac = {swift_optional_string(parsed['mac'])}\n"
        "    static let lines: [(ordinal: Int, qtyMilli: Int, grossSum: Int,\n"
        "                        discount: Int, netSum: Int, netUnitPrice: Int)] = [\n"
        f"{lines_rows}\n"
        "    ]\n"
        "\n"
        "    /// Every free-text line in the document, and the cashier attribute. The\n"
        "    /// parser must return NONE of this.\n"
        "    static let mustNotAppear: [String] = [\n"
        f"{must_not_appear_rows}\n"
        "    ]\n"
        "\n"
        "    /// All seven real receipts (S1-S7), keyed by their number in\n"
        "    /// tests/fixtures/fiscal_check_{n}.json and the spec's table —\n"
        "    /// seven documents from six register vendors, Python's own answers\n"
        "    /// for each. This is the parity pin that matters most.\n"
        "    struct Document {\n"
        "        let base64: String\n"
        "        let registerModel: String?\n"
        "        let fiscalTotal: Int\n"
        "        let mac: String?\n"
        "        let lines: [(ordinal: Int, qtyMilli: Int, grossSum: Int,\n"
        "                     discount: Int, netSum: Int, netUnitPrice: Int)]\n"
        "        let mustNotAppear: [String]\n"
        "    }\n"
        "    static let seven: [Int: Document] = [\n"
        f"{seven_block}\n"
        "    ]\n"
        "}\n",
        encoding="utf-8",
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    build_uuid5(OUT / "UUIDv5Fixture.swift")
    build_mapper(OUT / "MonobankMapperFixture.swift")
    build_check(OUT / "CheckFixture.swift")


if __name__ == "__main__":
    main()

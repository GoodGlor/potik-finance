import XCTest
@testable import MonitorFinance

/// The Swift parser against the Python one, on the same real document.
/// `CheckFixture` is generated from `scripts/check_decode.py`'s own answers —
/// so this suite fails if either implementation drifts, which is the point.
final class CheckXMLTests: XCTestCase {

    func testTheFuelDocumentParsesToPythonsNumbers() throws {
        let parsed = try CheckXML.parse(base64: CheckFixture.base64)

        XCTAssertEqual(parsed.registerModel, CheckFixture.registerModel)
        XCTAssertEqual(parsed.fiscalTotal, CheckFixture.fiscalTotal)
        XCTAssertEqual(parsed.mac, CheckFixture.mac)
        XCTAssertEqual(parsed.lines.count, CheckFixture.lines.count)

        for (got, want) in zip(parsed.lines, CheckFixture.lines) {
            XCTAssertEqual(got.ordinal, want.ordinal)
            XCTAssertEqual(got.qtyMilli, want.qtyMilli)
            XCTAssertEqual(got.grossSum, want.grossSum)
            XCTAssertEqual(got.discount, want.discount, "the <D> must join on <PP N>, not on position")
            XCTAssertEqual(got.netSum, want.netSum)
            XCTAssertEqual(got.netUnitPrice, want.netUnitPrice, "₴/л follows the money, not the pump")
        }
    }

    /// Cyrillic decoded as UTF-8 does not throw — it mangles. So the assertion
    /// is on the text, not on the absence of an error.
    func testTheNameIsReadAsWindows1251AndNotAsUtf8() throws {
        let parsed = try CheckXML.parse(base64: CheckFixture.base64)
        let name = try XCTUnwrap(parsed.lines.first?.name)
        XCTAssertFalse(name.isEmpty)
        XCTAssertFalse(name.contains("\u{FFFD}"), "replacement characters mean the wrong encoding")
        XCTAssertTrue(name.contains("А-95"), "the fuel grade survives the decode intact")
    }

    /// D9: free text and the cashier never leave this parser.
    func testNoFreeTextLineAndNoCashierNameSurvivesTheParse() throws {
        let parsed = try CheckXML.parse(base64: CheckFixture.base64)
        let everything = parsed.lines.map(\.name).joined(separator: "\n")
        for forbidden in CheckFixture.mustNotAppear {
            XCTAssertFalse(everything.contains(forbidden),
                           "«\(forbidden)» must not reach an item")
        }
    }

    func testGarbageIsRefusedRatherThanHalfParsed() {
        for bad in ["", "not base64 at all!!", Data("<RQ></RQ>".utf8).base64EncodedString()] {
            XCTAssertThrowsError(try CheckXML.parse(base64: bad), bad) { error in
                guard case .malformed = error as? TaxCabinetError else {
                    return XCTFail("expected .malformed for \(bad), got \(error)")
                }
            }
        }
    }

    /// The plan's one deliberate deviation from §2: items may total LESS than
    /// the receipt (an undetailed remainder, which `SplitMath` already absorbs)
    /// but never MORE, which is arithmetically impossible and means the parse
    /// is wrong.
    func testLinesMayUnderTotalTheReceiptButNeverOverTotalIt() throws {
        let under = try CheckXML.parse(base64: CheckXMLFixtures.document(total: 100_00, lines: [40_00, 30_00]))
        XCTAssertEqual(under.lines.count, 2)

        XCTAssertThrowsError(try CheckXML.parse(base64: CheckXMLFixtures.document(total: 100_00, lines: [60_00, 50_00])))
    }

    /// `_unit_price(6581, 2000)` is 3291 under `Decimal` half-up rounding and
    /// 3290 under float-plus-`round()` (banker's rounding to even). None of
    /// the seven real receipts' own numbers happen to land on this exact
    /// rounding boundary, so a `Double` mutation would pass every golden-value
    /// test in this file unnoticed — this is the case that tells the two
    /// implementations apart. Mirrors
    /// `test_the_unit_price_is_decimal_and_rounds_half_up_not_bankers` on the
    /// Python side.
    func testTheUnitPriceIsDecimalAndRoundsHalfUpNotBankers() throws {
        let parsed = try CheckXML.parse(base64: CheckXMLFixtures.singleLine(sum: 6581, qtyMilli: 2000))
        XCTAssertEqual(parsed.lines.first?.netUnitPrice, 3291)
    }

    // --- Seven receipts, six vendors (S1-S7) --------------------------------

    /// The Swift parser's pin against Python's own answers for all seven real
    /// receipts at once — `CheckFixture.seven`, generated by
    /// `scripts/build_ios_test_fixtures.py` from `scripts/check_decode.py`.
    /// The golden counts and totals are also hand-verified and hardcoded here
    /// (matching `tests/test_check_decode.py`'s own `GOLDEN` table), so this
    /// test does not only prove "Swift agrees with whatever Python currently
    /// says" — it proves both agree with the numbers the owner verified.
    func testAllSevenReceiptsAgreeWithPythonsGoldenNumbers() throws {
        let golden: [Int: (lines: Int, total: Int, exact: Bool)] = [
            1: (lines: 5, total: 126400, exact: true),
            2: (lines: 1, total: 6800, exact: true),
            3: (lines: 1, total: 79923, exact: true),
            4: (lines: 12, total: 124050, exact: false),
            5: (lines: 1, total: 99987, exact: true),
            6: (lines: 5, total: 49056, exact: true),
            7: (lines: 3, total: 61207, exact: true),
        ]

        for n in 1...7 {
            let fixture = try XCTUnwrap(CheckFixture.seven[n], "missing fixture for receipt \(n)")
            let want = try XCTUnwrap(golden[n])
            let parsed = try CheckXML.parse(base64: fixture.base64)

            XCTAssertEqual(parsed.lines.count, want.lines, "receipt \(n)")
            XCTAssertEqual(parsed.fiscalTotal, want.total, "receipt \(n)")
            XCTAssertEqual(parsed.fiscalTotal, fixture.fiscalTotal, "receipt \(n) vs Python's own total")
            XCTAssertEqual(parsed.registerModel, fixture.registerModel, "receipt \(n)")
            XCTAssertEqual(parsed.mac, fixture.mac, "receipt \(n)")

            let linesSum = parsed.lines.reduce(0) { $0 + $1.netSum }
            if want.exact {
                XCTAssertEqual(linesSum, want.total, "receipt \(n) lines must total its footer exactly")
            } else {
                // Receipt 4 (S5): lines under-total the footer by exactly
                // 209.87 UAH (20987 minor units) — named, not just "<=".
                XCTAssertEqual(want.total - linesSum, 20987, "receipt \(n) shortfall")
            }

            XCTAssertEqual(parsed.lines.count, fixture.lines.count, "receipt \(n)")
            for (got, wantLine) in zip(parsed.lines, fixture.lines) {
                XCTAssertEqual(got.ordinal, wantLine.ordinal, "receipt \(n)")
                XCTAssertEqual(got.qtyMilli, wantLine.qtyMilli, "receipt \(n) ordinal \(wantLine.ordinal)")
                XCTAssertEqual(got.grossSum, wantLine.grossSum, "receipt \(n) ordinal \(wantLine.ordinal)")
                XCTAssertEqual(got.discount, wantLine.discount, "receipt \(n) ordinal \(wantLine.ordinal)")
                XCTAssertEqual(got.netSum, wantLine.netSum, "receipt \(n) ordinal \(wantLine.ordinal)")
                XCTAssertEqual(got.netUnitPrice, wantLine.netUnitPrice, "receipt \(n) ordinal \(wantLine.ordinal)")
            }

            let everything = parsed.lines.map(\.name).joined(separator: "\n")
            for forbidden in fixture.mustNotAppear {
                XCTAssertFalse(everything.contains(forbidden), "receipt \(n): «\(forbidden)» must not reach an item")
            }
        }
    }

    /// S1: five of the seven put their goods in `<P>`; the two fuel stations
    /// (receipts 3, 5) use `<PP>`. A parser reading only one of the two
    /// elements returns zero lines for every receipt that uses the other.
    func testGoodsAreReadFromBothPAndPP() throws {
        for n in 1...7 {
            let fixture = try XCTUnwrap(CheckFixture.seven[n])
            let parsed = try CheckXML.parse(base64: fixture.base64)
            XCTAssertGreaterThan(parsed.lines.count, 0, "receipt \(n)")
        }
    }

    /// S2: most of receipts 1's, 4's and 6's goods elements carry only `C`,
    /// `NM`, `SM`, `TX` — no `Q`. Absent `Q` means one unit (1000 milli-units).
    /// A minority of lines in receipts 4 and 6 DO carry an explicit `Q` (sold
    /// by weight) and must keep it rather than being defaulted.
    func testGoodsWithoutQDefaultToOneUnit() throws {
        let one = try XCTUnwrap(CheckFixture.seven[1])
        let parsedOne = try CheckXML.parse(base64: one.base64)
        for line in parsedOne.lines {
            XCTAssertEqual(line.qtyMilli, 1000, "ordinal \(line.ordinal)")
            XCTAssertEqual(line.netUnitPrice, line.netSum, "ordinal \(line.ordinal)")
        }

        let four = try XCTUnwrap(CheckFixture.seven[4])
        let parsedFour = try CheckXML.parse(base64: four.base64)
        let fourByOrdinal = Dictionary(uniqueKeysWithValues: parsedFour.lines.map { ($0.ordinal, $0.qtyMilli) })
        XCTAssertEqual(fourByOrdinal[12], 2000)
        XCTAssertEqual(fourByOrdinal[15], 2000)
        for line in parsedFour.lines where line.ordinal != 12 && line.ordinal != 15 {
            XCTAssertEqual(line.qtyMilli, 1000, "ordinal \(line.ordinal)")
        }

        let six = try XCTUnwrap(CheckFixture.seven[6])
        let parsedSix = try CheckXML.parse(base64: six.base64)
        let sixByOrdinal = Dictionary(uniqueKeysWithValues: parsedSix.lines.map { ($0.ordinal, $0.qtyMilli) })
        XCTAssertEqual(sixByOrdinal[6], 5764)
        for line in parsedSix.lines where line.ordinal != 6 {
            XCTAssertEqual(line.qtyMilli, 1000, "ordinal \(line.ordinal)")
        }
    }

    /// S3: none of receipt 1's discounts carry `NI`. Without joining them to
    /// the nearest preceding goods element in document order, this receipt's
    /// lines out-total its own footer and the whole document is refused.
    func testReceiptOneProvesTheNILessDiscountFallback() throws {
        let one = try XCTUnwrap(CheckFixture.seven[1])
        let parsed = try CheckXML.parse(base64: one.base64)
        XCTAssertEqual(parsed.lines.count, 5)
        // Gross 3104.00, discounts 1840.00, net 1264.00 — the receipt's own total.
        XCTAssertEqual(parsed.lines.reduce(0) { $0 + $1.grossSum }, 310400)
        XCTAssertEqual(parsed.lines.reduce(0) { $0 + $1.discount }, 184000)
        XCTAssertEqual(parsed.lines.reduce(0) { $0 + $1.netSum }, parsed.fiscalTotal)
        XCTAssertEqual(parsed.fiscalTotal, 126400)
    }

    /// S6: receipt 2's `NM` contains a literal newline — product names are
    /// not single-line, and decoding must not choke on it or truncate the
    /// line. `.trimmingCharacters` only trims the ends, so the newline is
    /// expected to survive inside the name.
    func testReceiptTwoSurvivesALiteralNewlineInTheGoodsName() throws {
        let two = try XCTUnwrap(CheckFixture.seven[2])
        let parsed = try CheckXML.parse(base64: two.base64)
        XCTAssertEqual(parsed.lines.count, 1)
        XCTAssertEqual(parsed.fiscalTotal, 6800)
        let name = try XCTUnwrap(parsed.lines.first?.name)
        XCTAssertTrue(name.contains("\n"))
        XCTAssertEqual(parsed.lines.first?.netSum, 6800)
    }

    /// F4 (final review): two consecutive `<D>` elements with no `NI` both
    /// accumulate onto the same preceding goods line (S3's own fallback —
    /// see `testReceiptOneProvesTheNILessDiscountFallback`), which can drive
    /// that line's discount past its own gross sum. Not seen in any real
    /// fixture; a guard against a document that could still produce one.
    func testALinesDiscountDrivingItsSumNegativeIsRefused() {
        let bad = CheckXMLFixtures.doubledDiscount(grossSum: 100_00, discountEach: 60_00)
        XCTAssertThrowsError(try CheckXML.parse(base64: bad)) { error in
            guard case .malformed = error as? TaxCabinetError else {
                return XCTFail("expected .malformed, got \(error)")
            }
        }
    }
}

/// Hand-built `<RQ>` documents for totals the real fixture does not exhibit.
/// Named `CheckXMLFixtures` (not `Fixtures`) so it cannot collide with any
/// other helper in this test target.
private enum CheckXMLFixtures {
    /// A minimal windows-1251, base64-encoded `<RQ>` with one `<PP>` per
    /// line (no discount) and a footer totalling `total`.
    static func document(total: Int, lines: [Int]) -> String {
        let pp = lines.enumerated().map { index, sum in
            "<PP N=\"\(index + 1)\" NM=\"Тестова позиція\" Q=\"1000\" PRC=\"\(sum)\" SM=\"\(sum)\"></PP>"
        }.joined()
        let xml = """
        <?xml version="1.0" encoding="windows-1251"?><RQ NDv="ND-74"><DAT><C T="0">\
        \(pp)<E FN="0" N="0" NO="0" SM="\(total)" TS="20260101000000"></E></C></DAT>\
        <MAC>TEST</MAC></RQ>
        """
        let data = xml.data(using: .windowsCP1251) ?? Data()
        return data.base64EncodedString()
    }

    /// A single undiscounted `<P>` line whose gross (and so net) sum is
    /// `sum`, at the given `Q`, so `netUnitPrice` is exactly `sum / (qtyMilli
    /// / 1000)` — built to land on a rounding boundary the real fixtures
    /// never do.
    static func singleLine(sum: Int, qtyMilli: Int) -> String {
        let xml = """
        <?xml version="1.0" encoding="windows-1251"?><RQ NDv="ND-74"><DAT><C T="0">\
        <P N="1" NM="Тестова позиція" Q="\(qtyMilli)" SM="\(sum)"></P>\
        <E FN="0" N="0" NO="0" SM="\(sum)" TS="20260101000000"></E></C></DAT>\
        <MAC>TEST</MAC></RQ>
        """
        let data = xml.data(using: .windowsCP1251) ?? Data()
        return data.base64EncodedString()
    }

    /// One goods line followed by two NI-less `<D>` elements — S3's fallback
    /// joins both onto the same preceding line, doubling the discount.
    static func doubledDiscount(grossSum: Int, discountEach: Int) -> String {
        let xml = """
        <?xml version="1.0" encoding="windows-1251"?><RQ NDv="ND-74"><DAT><C T="0">\
        <PP N="1" NM="Тестова позиція" Q="1000" SM="\(grossSum)"></PP>\
        <D N="2" SM="\(discountEach)" TR="0" TX="0" TY="0"></D>\
        <D N="3" SM="\(discountEach)" TR="0" TX="0" TY="0"></D>\
        <E FN="0" N="4" NO="0" SM="0" TS="20260101000000"></E></C></DAT>\
        <MAC>TEST</MAC></RQ>
        """
        let data = xml.data(using: .windowsCP1251) ?? Data()
        return data.base64EncodedString()
    }
}
